export function page({ path, title, description, body, current, schema = [], noindex = false, bodyClass = '', head = '', scripts = [], bare = false, ogImage = '/media/og-gideon.png', ogType = 'website' }) {
  const canonical = `${SITE}${path === '/' ? '/' : path}`;
  const ld = schema.map((s) => `<script type="application/ld+json">${JSON.stringify(s).replace(/</g, '\\u003c')}</script>`).join('\n');
  const moduleScripts = scripts.map((s) => `<script type="module" src="${s}"></script>`).join('\n');
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
${noindex ? '<meta name="robots" content="noindex">' : `<link rel="canonical" href="${canonical}">`}
<meta property="og:site_name" content="Gideon">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(description)}">
<meta property="og:type" content="${ogType}">
<meta property="og:url" content="${canonical}">
<meta property="og:image" content="${SITE}${ogImage}">
<meta name="twitter:card" content="summary_large_image">
<meta name="theme-color" content="#050608">
<link rel="icon" type="image/png" sizes="32x32" href="/media/favicon-32.png">
<link rel="apple-touch-icon" href="/media/mark-180.png">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Archivo:wdth,wght@100..125,500..800&family=Inter:wght@400;500;600&family=JetBrains+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="/assets/site.css">
${head}
<script src="/assets/site.js" defer></script>
${ld}
</head>
<body class="${bodyClass}">
${bare ? body : `${header(current)}\n<main>${body}</main>\n${footer()}`}
${moduleScripts}
</body>
</html>
`;
}

